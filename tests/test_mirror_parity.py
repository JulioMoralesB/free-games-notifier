"""Cross-language parity for GET /games/history: Python API vs. the Cloudflare mirror.

The dashboard calls /games/history, which the mirror (cloudflare/mirror/)
re-implements in TypeScript. Both sides are pinned to one shared fixture:

- this test asserts the real FastAPI route produces the fixture's expected
  results (and that the fixture's games are exactly what the mirror push sends);
- cloudflare/mirror/test/parity.test.ts asserts the Worker produces the same.

If you change /games/history semantics on purpose, regenerate the fixture with
``python -m tests.test_mirror_parity`` and update the Worker until its test passes.
"""

import itertools
import json
import os
from unittest.mock import patch

import pytest
from fastapi.testclient import TestClient

from api.serializers import to_game_item_dict
from modules.models import FreeGame

FIXTURE_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "cloudflare", "mirror", "test", "fixtures", "history-parity.json",
)


def _game(title, store, end_date, **extra):
    return FreeGame(
        title=title,
        store=store,
        url=f"https://{store}.example.com/{title.lower()}",
        image_url=f"https://{store}.example.com/{title.lower()}.jpg",
        original_price=extra.get("original_price"),
        end_date=end_date,
        is_permanent=False,
        description=f"About {title}",
        review_scores=extra.get("review_scores", []),
        game_type=extra.get("game_type", "game"),
    )


# Far past / far future dates keep the status filter independent of "now".
# Covers: case-insensitive title sort (incl. non-ASCII), an end_date tie,
# naive and offset timestamps (sorted as raw text, filtered as instants),
# and empty / unparseable end_date (expired in /games/history).
SOURCE_GAMES = [
    _game("Alpha", "epic", "2099-03-01T16:00:00.000Z", review_scores=["Metascore: 88"]),
    _game("beta", "steam", "2099-01-15T17:00:00Z", original_price="$9.99"),
    _game("Gamma", "epic", "2020-05-01T15:00:00.000Z"),
    _game("Delta", "steam", "2021-01-01T00:00:00Z", game_type="dlc"),
    _game("Épsilon", "epic", "2099-03-01T16:00:00.000Z"),
    _game("Zeta", "epic", ""),
    _game("eta", "steam", "2099-02-01T10:00:00"),
    _game("Theta", "epic", "2099-02-01T05:00:00-06:00"),
    _game("Iota", "steam", "someday", review_scores=["Very Positive", "Metascore: 70"]),
]


def _query_cases():
    cases = [
        {"sort_by": s, "sort_dir": d, "store": st, "status": stat, "limit": 100, "offset": 0}
        for s, d, st, stat in itertools.product(
            ("end_date", "title"), ("asc", "desc"), ("all", "epic", "steam"), ("all", "active", "expired")
        )
    ]
    cases += [
        {"sort_by": "end_date", "sort_dir": "desc", "store": "all", "status": "all", "limit": 3, "offset": 0},
        {"sort_by": "end_date", "sort_dir": "desc", "store": "all", "status": "all", "limit": 3, "offset": 3},
        {"sort_by": "title", "sort_dir": "asc", "store": "all", "status": "all", "limit": 4, "offset": 8},
    ]
    return cases


def _history(client, games, params):
    with patch("api.routes.games.load_previous_games", return_value=list(games)):
        response = client.get("/games/history", params=params)
    assert response.status_code == 200, response.text
    return response.json()


def _build_fixture():
    from api import app

    client = TestClient(app)
    return {
        "_comment": "Generated by `python -m tests.test_mirror_parity`. Do not edit by hand.",
        "games": [to_game_item_dict(g) for g in SOURCE_GAMES],
        "cases": [
            {
                "query": params,
                "total": (body := _history(client, SOURCE_GAMES, params))["total"],
                "titles": [g["title"] for g in body["games"]],
            }
            for params in _query_cases()
        ],
    }


@pytest.fixture(scope="module")
def fixture_data():
    with open(FIXTURE_PATH, encoding="utf-8") as f:
        return json.load(f)


def test_fixture_games_are_exactly_what_the_mirror_push_sends(fixture_data):
    assert fixture_data["games"] == [to_game_item_dict(g) for g in SOURCE_GAMES]


def test_python_history_endpoint_matches_the_fixture(fixture_data):
    """If this fails, /games/history changed: regenerate the fixture and fix the Worker."""
    assert _build_fixture() == fixture_data


if __name__ == "__main__":
    os.makedirs(os.path.dirname(FIXTURE_PATH), exist_ok=True)
    with open(FIXTURE_PATH, "w", encoding="utf-8") as f:
        json.dump(_build_fixture(), f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"Wrote {FIXTURE_PATH}")
